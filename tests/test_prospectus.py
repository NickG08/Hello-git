"""Prospectus term parsing, on text fragments taken from real KASE prospectuses."""

from kzbonds.prospectus import parse_terms

FULL_FORM_MFSCB7 = """
5. Получение дохода по облигациям: 1) размер ставки основного вознаграждения по облигациям
Ставка купонного вознаграждения является фиксированной на весь срок обращения Облигаций
и составляет 10,5 (десять целых пять десятых) % (процента) годовых от номинальной стоимости Облигаций.
2) периодичность выплаты вознаграждения и (или) даты выплаты вознаграждения по облигациям
Выплата вознаграждения по Облигациям производится 12 (двенадцать) раз в год ежемесячно с
даты начала обращения Облигаций в течение всего срока обращения Облигаций.
3) срок обращения облигаций (не заполняется в случае выпуска облигаций без срока погашения)
     Годы                     Месяцы                   Дни
     1                        6                        0
"""

PROGRAM_FORM_ALMSPP1 = """
1) размер ставки основного вознаграждения по облигациям и дополнительного вознаграждения в
случае его наличия cтавка основного вознаграждения: 7% (семь процентов) годовых от номинальной
стоимости Облигации дополнительное вознаграждение: 0 %
2) периодичность выплаты вознаграждения: Выплата вознаграждения по Облигациям производится
4 (четыре) раза в год через каждые три месяца с даты начала обращения Облигаций.
6) дата начала и срок обращения облигаций Дата начала обращения Облигаций является датой
проведения первых состоявшихся торгов по размещению Облигаций.
Бұл құжат ҚР 2003 жылдың 7 қаңтарындағы "Электронды құжат және электронды cандық қол қою"
туралы заңның 7 бабы, 1 тармағына cәйкеc қағаз бетіндегі заңмен тең.
срок обращения облигаций Лет: 1 Месяцев: 2 7) дата и способ погашения облигаций
"""


def test_full_form_prospectus():
    t = parse_terms(FULL_FORM_MFSCB7)
    assert t == {"term_months": 18, "coupon_rate": 10.5, "coupon_status": "fixed", "coupon_freq": 12}


def test_program_form_with_latin_letters_and_signature_boilerplate():
    t = parse_terms(PROGRAM_FORM_ALMSPP1)
    assert t["coupon_rate"] == 7.0
    assert t["coupon_freq"] == 4
    assert t["term_months"] == 14


def test_rate_written_as_word():
    # MFLNpp1: "ставка основного вознаграждения: двенадцать дополнительное вознаграждение: 0 %"
    t = parse_terms("cтавка основного вознаграждения: двенадцать дополнительное вознаграждение: 0 %")
    assert (t["coupon_rate"], t["coupon_status"]) == (12.0, "fixed")


def test_rate_set_at_placement():
    text = (
        "ставка основного вознаграждения: фиксированная, будет определена по итогам проведения "
        "первых состоявшихся торгов по размещению облигаций дополнительное вознаграждение: %"
    )
    t = parse_terms(text)
    assert (t["coupon_rate"], t["coupon_status"]) == (None, "at_placement")


def test_floating_rate():
    text = (
        "ставка основного вознаграждения: Ставка вознаграждения по Облигациям является плавающей "
        "на весь срок обращения Облигаций. дополнительное вознаграждение: %"
    )
    assert parse_terms(text)["coupon_status"] == "floating"


def test_monthly_payments_described_per_month():
    # LZGRb22: "6 (шесть) раз за период обращения облигаций через каждый 1 (один) месяц"
    text = (
        "сроки выплаты вознаграждения по облигациям: Выплата вознаграждения по облигациям производится "
        "6 (шесть) раз за период обращения облигаций через каждый 1 (один) месяц. "
        "Срок обращения облигаций: Дни: 180"
    )
    t = parse_terms(text)
    assert t["coupon_freq"] == 12
    assert t["term_months"] == 6


def test_english_aix_terms():
    text = (
        "Interest rate risk: the Bonds bear a fixed coupon rate of 5% per annum. "
        "Bond circulation – period of 10 years until 26 June 2036"
    )
    t = parse_terms(text)
    assert (t["coupon_rate"], t["term_months"]) == (5.0, 120)
